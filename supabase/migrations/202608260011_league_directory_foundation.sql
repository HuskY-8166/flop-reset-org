do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'competition_sources',
    'external_team_sources',
    'competition_entries',
    'league_players',
    'competition_roster_members',
    'external_source_snapshots',
    'identity_reconciliation_queue',
    'admin_audit_log',
    'page_content_overrides'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);

    if not exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename = table_name
        and policyname = table_name || '_admin_read'
    ) then
      execute format(
        'create policy %I on public.%I for select to authenticated using (coalesce((auth.jwt() -> ''app_metadata'' ->> ''site_admin'')::boolean, false))',
        table_name || '_admin_read', table_name
      );
    end if;

    if not exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename = table_name
        and policyname = table_name || '_admin_write'
    ) then
      execute format(
        'create policy %I on public.%I for all to authenticated using (coalesce((auth.jwt() -> ''app_metadata'' ->> ''site_admin'')::boolean, false)) with check (coalesce((auth.jwt() -> ''app_metadata'' ->> ''site_admin'')::boolean, false))',
        table_name || '_admin_write', table_name
      );
    end if;
  end loop;
end $$;

-- Public pages use deliberately narrow projections. The base tables remain
-- admin-only so notes, manual values, lock state, reconciliation evidence,
-- and admin identifiers cannot leak through PostgREST.
create or replace view public.public_competition_entries
with (security_barrier = true)
as
select
  e.entry_id,
  e.competition_id,
  e.fr_team_id,
  e.opponent_id,
  e.slug,
  e.display_name_snapshot,
  e.logo_url_snapshot,
  e.tier,
  e.seed,
  e.registration_status,
  e.competitive_status,
  e.is_power_tracked,
  e.status,
  e.joined_at,
  e.left_at,
  e.created_at,
  e.updated_at,
  c.name as competition_name,
  c.format as competition_format,
  c.league_name as competition_league_name,
  c.circuit_name as competition_circuit_name,
  c.season_year as competition_season_year,
  c.region as competition_region
from public.competition_entries e
join public.competitions c on c.id = e.competition_id;

create or replace view public.public_league_players
with (security_barrier = true)
as
select
  league_player_id,
  slug,
  canonical_name,
  display_name,
  linked_fr_player_id,
  status,
  country,
  aliases,
  created_at,
  updated_at
from public.league_players;

create or replace view public.public_competition_roster_members
with (security_barrier = true)
as
select
  r.roster_member_id,
  r.entry_id,
  r.league_player_id,
  r.display_name_snapshot,
  r.role,
  r.status,
  r.is_current,
  r.source_url,
  r.joined_at,
  r.left_at,
  r.created_at,
  r.updated_at,
  e.competition_id,
  e.slug as entry_slug,
  e.display_name_snapshot as entry_display_name,
  e.tier as entry_tier,
  lp.slug as league_player_slug,
  lp.display_name as league_player_display_name,
  c.name as competition_name,
  c.format as competition_format,
  c.league_name as competition_league_name,
  c.circuit_name as competition_circuit_name,
  c.season_year as competition_season_year,
  c.region as competition_region
from public.competition_roster_members r
join public.competition_entries e on e.entry_id = r.entry_id
join public.competitions c on c.id = e.competition_id
left join public.league_players lp on lp.league_player_id = r.league_player_id;

create or replace view public.public_page_content_overrides
with (security_barrier = true)
