comment on table public.competition_entries is 'Authoritative competition-scoped participant directory. Tier and registration state belong here, not on timeless team identity.';
comment on column public.competition_entries.source_registration_key is 'Competition-scoped idempotency key. It is not proof of canonical team identity.';
comment on table public.competition_roster_members is 'Event roster history. Removal closes a membership row instead of deleting it.';
comment on table public.external_source_snapshots is 'Last-good normalized source evidence. Public pages never fetch Rivalry directly.';
comment on table public.identity_reconciliation_queue is 'Human review queue. Name similarity never authorizes an automatic canonical merge.';

