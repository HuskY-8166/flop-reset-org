create table if not exists public.competition_entries (
  entry_id bigint generated by default as identity primary key,
  competition_id bigint not null references public.competitions(id) on delete restrict,
  fr_team_id bigint references public.teams(id) on delete restrict,
  opponent_id bigint references public.opponents(opponent_id) on delete restrict,
  external_source_id bigint references public.external_team_sources(source_id) on delete set null,
  source_registration_key text,
  slug text not null unique,
  display_name_snapshot text not null,
  logo_url_snapshot text,
  tier text,
  seed integer,
  registration_status text not null default 'registered',
  competitive_status text not null default 'pending',
  is_power_tracked boolean not null default false,
  source_provider text,
  source_external_id text,
  source_url text,
  source_values jsonb not null default '{}'::jsonb,
  manual_values jsonb not null default '{}'::jsonb,
  locked_fields jsonb not null default '[]'::jsonb,
  notes text,
  status text not null default 'active',
  joined_at timestamptz,
  left_at timestamptz,
  updated_by_admin uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (num_nonnulls(fr_team_id, opponent_id) <= 1),
  check (
    fr_team_id is not null
    or opponent_id is not null
    or external_source_id is not null
    or source_registration_key is not null
  )
);

create unique index if not exists competition_entries_fr_team_unique
  on public.competition_entries(competition_id, fr_team_id)
  where fr_team_id is not null;
create unique index if not exists competition_entries_opponent_unique
  on public.competition_entries(competition_id, opponent_id)
  where opponent_id is not null;
create unique index if not exists competition_entries_source_registration_unique
  on public.competition_entries(competition_id, source_provider, source_registration_key)
  where source_provider is not null and source_registration_key is not null;

create table if not exists public.league_players (
